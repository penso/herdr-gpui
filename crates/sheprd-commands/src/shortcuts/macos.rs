use crate::Command;

pub(super) fn defaults(command: Command) -> &'static [&'static str] {
    use Command::*;
    match command {
        OpenNotificationTarget => &["cmd-alt-n"],
        NewWindow => &["cmd-alt-shift-n"],
        Workspace => &["cmd-shift-n"],
        NewWorktree => &["cmd-n"],
        Tab => &["cmd-t"],
        SplitRight => &["cmd-d"],
        SplitDown => &["cmd-shift-d"],
        NextTab => &["cmd-shift-]"],
        PreviousTab => &["cmd-shift-["],
        FocusLeft => &["cmd-alt-left"],
        FocusRight => &["cmd-alt-right"],
        FocusUp => &["cmd-alt-up"],
        FocusDown => &["cmd-alt-down"],
        NextPane => &["cmd-alt-]"],
        PreviousPane => &["cmd-alt-["],
        Back => &["cmd-["],
        Forward => &["cmd-]"],
        Zoom => &["cmd-shift-enter"],
        ClearPane => &["cmd-k"],
        Find => &["cmd-f"],
        FindNext => &["cmd-g"],
        FindPrevious => &["cmd-shift-g"],
        CopyMode => &["cmd-shift-c"],
        AnnotateSelection => &["cmd-shift-a"],
        ClosePane => &["cmd-w"],
        CloseTab => &["cmd-shift-w"],
        ReopenClosedTab => &["cmd-shift-t"],
        TabNumber(1) => &["cmd-1"],
        TabNumber(2) => &["cmd-2"],
        TabNumber(3) => &["cmd-3"],
        TabNumber(4) => &["cmd-4"],
        TabNumber(5) => &["cmd-5"],
        TabNumber(6) => &["cmd-6"],
        TabNumber(7) => &["cmd-7"],
        TabNumber(8) => &["cmd-8"],
        TabNumber(9) => &["cmd-9"],
        ToggleSidebar => &["cmd-b"],
        ToggleStatusBar => &["cmd-alt-b"],
        // F6 alone is Windows' region key; on a Mac it stays the app's.
        FocusNextRegion => &["cmd-f6"],
        FocusPreviousRegion => &["cmd-shift-f6"],
        ToggleZenMode => &["ctrl-cmd-z"],
        IncreaseFontSize => &["cmd-=", "cmd-+"],
        DecreaseFontSize => &["cmd--"],
        ResetFontSize => &["cmd-0"],
        Settings => &["cmd-,"],
        Keybinds => &["cmd-/"],
        Sessions => &["cmd-shift-s"],
        WorkspacePicker => &["cmd-p"],
        Palette => &["cmd-shift-p"],
        ResumePalette => &["cmd-shift-r"],
        GoToSymbol => &["cmd-shift-o"],
        GoToFile => &["cmd-o"],
        Quit => &["cmd-q"],
        NewBrowserTab => &["cmd-shift-b"],
        SplitEditor => &["cmd-\\"],
        ToggleFullScreen => &["ctrl-cmd-f"],
        CycleWindows => &["cmd-`"],
        CloseWindow => &["cmd-alt-shift-w"],
        _ => &[],
    }
}
